def phone_key(value):
    digits = re.sub(r'\D', '', value)
    if len(digits)==12 and digits.startswith('91'):
        digits = digits[2:]
    return digits


def matching_patients(name='', email='', phone='', mrn=''):
    query = Q(email__iexact=email) if email else Q(pk__in=[])
    if name:
        query |= Q(name__iexact=' '.join(name.split()))
    if mrn:
        try:
            query |= Q(registration__mrn=uuid.UUID(mrn.removeprefix('MN-').removeprefix('mn-')))
        except ValueError:
            pass
    keys = [phone_key(phone)] if phone and len(phone_key(phone)) >= 7 else []
    # Phone formatting differs in older records. Normalize in SQL without altering those records.
    if keys:
        from django.db.models.functions import Replace
        from django.db.models import Value
        normalized = Replace(Replace(Replace(Replace(Replace('phone', Value(' '), Value('')), Value('-'), Value('')), Value('('), Value('')), Value(')'), Value('')), Value('+'), Value(''))
        query |= Q(phone_digits__in=[keys[0], '91'+keys[0]])
        records = User.objects.filter(role='patient').annotate(phone_digits=normalized)
    else:
        records = User.objects.filter(role='patient')
    return records.filter(query).select_related('registration').order_by('name','pk')


class PatientForm(forms.Form):
    name = forms.CharField(max_length=120, label='Patient full name')
    email = forms.EmailField(max_length=254, label='Email address')
    phone = forms.CharField(max_length=20, label='Mobile phone number')
    date_of_birth = forms.DateField(required=False, widget=forms.DateInput(attrs={'type':'date'}))
    address = forms.CharField(max_length=600, required=False, widget=forms.Textarea(attrs={'rows':2}))
    emergency_name = forms.CharField(max_length=120, required=False, label='Emergency contact name')
    emergency_phone = forms.CharField(max_length=20, required=False, label='Emergency contact phone')
    existing_mrn = forms.CharField(max_length=40, required=False, label='Existing MedNova MRN (lookup only)', help_text='If a patient already has a MedNova MRN, select their existing record. New MRNs are generated by the hospital system.')
    duplicate_reviewed = forms.BooleanField(required=False, label='I checked the matches below. This is a different person sharing a name or phone; create a separate record.')
    consent = forms.BooleanField(label='The patient authorized recording these registration details for hospital care.')

    def clean_name(self):
        name = ' '.join(self.cleaned_data['name'].split())
        if len(name)<2 or not any(ch.isalpha() for ch in name) or any(ch.isdigit() for ch in name):
            raise forms.ValidationError('Enter a patient name with letters, not numbers.')
        return name

    def clean_email(self):
        return self.cleaned_data['email'].strip().lower()

    def clean_phone(self):
        raw = self.cleaned_data['phone'].strip()
        if re.search(r'[^\d+ ()-]', raw):
            raise forms.ValidationError('Use digits and an optional international country code.')
        value = phone_key(raw)
        if raw.startswith('+') and 11 <= len(value) <= 15 and not value.startswith('0'):
            return '+'+value
        if not re.fullmatch(r'[6-9]\d{9}',value):
            raise forms.ValidationError('Enter a 10-digit Indian mobile, optionally +91, or an international number with +country code.')
        return value

    def clean_emergency_phone(self):
        from .forms import clean_phone
        value = self.cleaned_data.get('emergency_phone','')
        if value and not 7 <= len(phone_key(value)) <= 15:
            raise forms.ValidationError('Enter a valid emergency contact phone number.')
        return clean_phone(value)

    def clean_date_of_birth(self):
        value = self.cleaned_data.get('date_of_birth')
        if value and (value>timezone.localdate() or (timezone.localdate().year-value.year)>130):
            raise forms.ValidationError('Enter a realistic date of birth that is not in the future.')
        return value


@db_errors
@roles('receptionist','admin')
@require_http_methods(['GET'])
def desk(request):
    from .payments import verification_queue
    first,last=day_bounds(timezone.localdate())
    visits=Appointment.objects.filter(slot__start__gte=first,slot__start__lt=last).select_related('patient','slot__doctor','payment')
    counts=dict(visits.values('status').annotate(total=Count('pk')).values_list('status','total'))
    return render(request,'care/reception_desk.html',{'payment_queue':verification_queue(request.user)[:5], 'visits':visits.order_by('slot__start')[:12], 'today_total':sum(counts.values()),
        'counts':counts,'waiting':QueueEntry.objects.filter(date=timezone.localdate(),status__in=['waiting','called']).count(),
        'recent':User.objects.filter(role='patient').select_related('registration').order_by('-date_joined')[:8]})


@db_errors
@roles('receptionist','admin')
@rate_limit('desk_registration',20,60)
@require_http_methods(['GET','POST'])
def register(request):
    form=PatientForm(request.POST if request.method=='POST' else None)
    matches=User.objects.none()
    if request.method=='POST':
        valid=form.is_valid()
        if valid:
            data=form.cleaned_data
            try:
                with transaction.atomic():
                    # Serialize front-desk registration across accounts, including shared-phone duplicate review.
                    # Existing department rows provide a stable mutex; no patient record is rewritten.
                    Department.objects.select_for_update().order_by('pk').first()
                    matches=matching_patients(data['name'],data['email'],data['phone'],data.get('existing_mrn',''))
                    if User.objects.filter(email__iexact=data['email']).exists():
                        form.add_error('email','This email belongs to an existing account. Select the patient below if it is the correct record; no existing data was changed.')
                    elif data.get('existing_mrn'):
                        form.add_error('existing_mrn','Use patient search to select an existing MRN. A supplied MRN never replaces or creates an identifier.')
                    elif matches.exists() and not data['duplicate_reviewed']:
                        form.add_error(None,'Possible existing patient. Review and select a match, or confirm a genuinely different person. No records were merged.')
                    else:
                        patient=User.objects.create_user(data['email'],None,name=data['name'],phone=data['phone'],date_of_birth=data.get('date_of_birth'),role='patient',approval='approved')
                        record,_=PatientRegistration.objects.get_or_create(patient=patient)
                        record.address,record.emergency_name,record.emergency_phone,record.consent=data['address'],data['emergency_name'],data['emergency_phone'],data['consent']
                        record.save()
                        audit(request.user,'reception.patient_registered',patient.pk)
                        messages.success(request,'Patient registered and MRN issued. No password was chosen by staff. Portal access can be set up by the patient through the existing verified email reset process, when email is configured.')
                        return redirect('reception_patient',patient_id=patient.pk)
            except IntegrityError:
                form.add_error('email','This account was registered by another request. Search the patient directory before retrying.')
    return render(request,'care/reception_register.html',{'form':form,'matches':matches[:20]})


