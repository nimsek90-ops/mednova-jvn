@db_errors
@roles('receptionist')
@require_http_methods(['GET'])
def booking_start(request):
    query=request.GET.get('q','').strip()[:100]
    records=User.objects.filter(role='patient',is_active=True,approval='approved').select_related('registration')
    if query:
        records=matching_patients(query,query,query,query).filter(is_active=True,approval='approved') | records.filter(Q(name__icontains=query)|Q(email__icontains=query)|Q(phone__icontains=query))
    return render(request,'care/reception_booking.html',{'patients':paged(request,records.order_by('name','pk')),'q':query})


class SpecialtyForm(forms.ModelForm):
    class Meta:
        model=Specialty
        fields=['name','departments','active']

    def clean_name(self):
        from .models import specialty_key
        name=' '.join(self.cleaned_data['name'].split())
        existing=Specialty.objects.filter(normalized_name=specialty_key(name)).exclude(pk=self.instance.pk)
        if existing.exists():
            raise forms.ValidationError('That specialty already exists. Edit its existing record.')
        return name

    def clean(self):
        data=super().clean()
        if self.instance.pk and data.get('departments') is not None and self.instance.doctors.exclude(department__in=data['departments']).exists():
            raise forms.ValidationError('This would remove the department of an assigned doctor. Update the verified doctor assignments first.')
        return data


@db_errors
@require_http_methods(['GET'])
def catalogue(request):
    query=request.GET.get('q','').strip()[:100]
    records=Specialty.objects.prefetch_related('departments').annotate(doctor_count=Count('doctors',filter=Q(doctors__user__role='doctor',doctors__user__is_active=True,doctors__user__approval='approved',doctors__department__active=True),distinct=True))
    if not (request.user.is_authenticated and request.user.role=='admin' and request.user.approval=='approved'):
        records=records.filter(active=True)
    if query:
        records=records.filter(Q(name__icontains=query)|Q(departments__name__icontains=query)).distinct()
    return render(request,'care/specialties.html',{'specialties':paged(request,records.order_by('name')),'q':query})


@db_errors
@roles('admin')
@require_http_methods(['GET','POST'])
def specialty_edit(request,pk=None):
    obj=get_object_or_404(Specialty,pk=pk) if pk else None
    form=SpecialtyForm(request.POST if request.method=='POST' else None,instance=obj)
    if request.method=='POST' and form.is_valid():
        try:
            with transaction.atomic():
                obj=form.save();audit(request.user,'specialty.saved',obj.pk)
            return redirect('specialty_catalogue')
        except IntegrityError:
            form.add_error('name','A matching specialty already exists.')
    return render(request,'care/specialty_edit.html',{'form':form})


@db_errors
@roles('admin')
@require_http_methods(['GET','POST'])
def doctor_specialties(request,doctor_id):
    profile=get_object_or_404(DoctorProfile.objects.select_related('user','department'),user_id=doctor_id,user__role='doctor')
    class AssignmentForm(forms.Form):
        specialties=forms.ModelMultipleChoiceField(queryset=Specialty.objects.filter(active=True,departments=profile.department).distinct(),required=False)
    form=AssignmentForm(request.POST if request.method=='POST' else None,initial={'specialties':profile.specialties.all()})
    if request.method=='POST' and form.is_valid():
        with transaction.atomic():
            DoctorProfile.objects.select_for_update().get(pk=profile.pk)
            profile.specialties.set(form.cleaned_data['specialties'])
            audit(request.user,'doctor.specialties_updated',profile.user_id)
        return redirect('doctor_detail',pk=profile.user_id)
    return render(request,'care/doctor_specialties.html',{'form':form,'profile':profile})
